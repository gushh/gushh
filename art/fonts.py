ACUTE_BASE = {"Á": "A", "É": "E", "Í": "I", "Ó": "O", "Ú": "U",
              "á": "a", "é": "e", "í": "i", "ó": "o", "ú": "u"}


def _compose(font, small):
    """Add accented letters (acute + tilde) built from their base glyphs."""
    for acc, base in ACUTE_BASE.items():
        if base not in font:
            continue
        top, rows = font[base]
        w = len(rows[0])
        if base == "i":
            font[acc] = (-1, [".#", "#.", ".."] + ["#." for _ in range(5)])
            continue
        c = w // 2
        r0 = "." * (c + 1) + "#" + "." * (w - c - 2) if c + 1 < w else "." * (w - 1) + "#"
        r1 = "." * c + "#" + "." * (w - c - 1)
        if small:
            # one-pixel accent sitting above a one-row gap
            font[acc] = (top - 2, [r0[:w], "." * w] + rows)
        else:
            font[acc] = (top - 3, [r0[:w], r1, "." * w] + rows)
    if small:
        n = font.get("N")
        if n:
            font["Ñ"] = (-2, [".##.", "...."] + n[1])
    else:
        font["Ñ"] = (-3, [".##.#", "#.##.", "....."] + font["N"][1])
        font["ñ"] = (-1, [".##.#", "#.##.", "....."] + font["n"][1])
    return font


